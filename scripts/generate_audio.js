/* =========================================================================
   OFFLINE AUDIO GENERATION  —  node scripts/generate_audio.js   (npm run generate-audio)

   • Builds the list of `phrases` from src/utils/narration.js (getAllNarration),
     so on-screen narration and pre-generated audio can never drift apart.
   • Applies per-style ElevenLabs voice settings (stability, similarity_boost,
     style, use_speaker_boost).
   • Calls the ElevenLabs text-to-speech API with the key from .env.local
     (VITE_ELEVENLABS_API_KEY).
   • Saves .mp3 files to public/assets/audio/ with slugified names.
   • Rewrites src/utils/audioMap.js  ( exact text  ->  /assets/audio/file.mp3 ).
   • Rate-limits at 500 ms between API calls. Re-running is safe: lines that
     already have an .mp3 are skipped  (use --force to regenerate everything).

   Adding a line by hand?  Push it into EXTRA_PHRASES below
   (paragraph / question text only — NEVER titles).
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VOICE_ID, MODEL_ID, STYLE_SETTINGS } from '../src/utils/audio.js';
import { getAllNarration } from '../src/utils/narration.js';
import { audioMap as existingMap } from '../src/utils/audioMap.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');
const FORCE = process.argv.includes('--force');

/* Hand-added lines go here, e.g.
   { text: "Here is my new pedagogical line!", style: 'statement' }, */
const EXTRA_PHRASES = [];

const phrases = [...getAllNarration(), ...EXTRA_PHRASES];

/* ---- read API key from .env.local (no external dependency) ------------- */
function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  const envPath = path.join(ROOT, '.env.local');
  if (!fs.existsSync(envPath)) return '';
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*(.+?)\s*$/);
    if (m) return m[1].replace(/^["']|["']$/g, '');
  }
  return '';
}
const API_KEY = readEnvKey();
if (!API_KEY) {
  console.error('✖ VITE_ELEVENLABS_API_KEY not found in .env.local');
  process.exit(1);
}

const sleep = ms => new Promise(r => setTimeout(r, ms));
const slugify = t =>
  t.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 48);

async function synthesize(text, style, attempt = 1) {
  const cfg = STYLE_SETTINGS[style] || STYLE_SETTINGS.statement;
  const res = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'audio/mpeg', 'xi-api-key': API_KEY },
      body: JSON.stringify({
        text,
        model_id: MODEL_ID,
        voice_settings: {
          stability: cfg.stability,
          similarity_boost: cfg.similarity_boost,
          style: cfg.style,
          use_speaker_boost: cfg.use_speaker_boost
        }
      })
    }
  );
  if (res.status === 401) throw new Error('401 Unauthorized — check VITE_ELEVENLABS_API_KEY');
  if ((res.status === 429 || res.status >= 500) && attempt < 5) {
    await sleep(2000 * attempt);
    return synthesize(text, style, attempt + 1);
  }
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  return Buffer.from(await res.arrayBuffer());
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  console.log(`Voice: Alice (${VOICE_ID}) · Model: ${MODEL_ID}`);
  console.log(`${phrases.length} phrases to process${FORCE ? ' (--force)' : ''}\n`);

  const newMap = {};
  let made = 0, skipped = 0, failed = 0;

  for (let i = 0; i < phrases.length; i++) {
    const { text, style } = phrases[i];
    const file = `audio_${slugify(text)}_${i}.mp3`;
    const urlPath = `/assets/audio/${file}`;
    const abs = path.join(OUT_DIR, file);

    // reuse an existing file if this exact text was generated before
    const prev = existingMap[text];
    if (!FORCE && prev && fs.existsSync(path.join(ROOT, 'public', prev))) {
      newMap[text] = prev;
      skipped++;
      continue;
    }
    try {
      const buf = await synthesize(text, style);
      fs.writeFileSync(abs, buf);
      newMap[text] = urlPath;
      made++;
      console.log(`✔ [${i + 1}/${phrases.length}] (${style}) ${file}`);
    } catch (err) {
      failed++;
      console.error(`✖ [${i + 1}/${phrases.length}] ${file}: ${err.message}`);
      if (/401/.test(err.message)) break;
    }
    await sleep(500); // rate limit
  }

  const body =
    '/* AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  ->  Value: pre-generated .mp3 in public/assets/audio/ */\n' +
    'export const audioMap = ' + JSON.stringify(newMap, null, 2) + ';\n';
  fs.writeFileSync(MAP_FILE, body);

  console.log(`\nDone. generated ${made}, reused ${skipped}, failed ${failed}.`);
  console.log('audioMap.js updated. Run `npm run clean-audio` to remove orphaned files.');
  if (failed) process.exitCode = 1;
}
main();
